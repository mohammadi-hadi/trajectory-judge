"""Turn the committed benchmark JSON into bench/README.md.

The split matters. These numbers are timings, so they are not byte-reproducible and CI cannot
regenerate them: the JSON is written by hand on a named machine and committed. What CI *can*
do is re-render the markdown from that JSON and diff it, which is what `--check` is for. So a
number cannot be typed into the table (the table is generated), and it cannot be quietly edited
into the JSON either, because the JSON carries its own provenance block.

That is the same split the project already uses in ci.yml, where results/tables are diffed and
results/figures are not.

    python bench/render.py                 # rewrite bench/README.md
    python bench/render.py --check         # fail if it would change
"""

from __future__ import annotations

import argparse
import itertools
import json
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).parent
HEADER = "<!-- generated by bench/render.py from bench/results/*.json; do not edit -->"
BENCH_START = "<!-- BENCH:START -->"
BENCH_END = "<!-- BENCH:END -->"


def _row(s: dict[str, Any]) -> str:
    scraped = s.get("scraped_overhead_p99_ms")
    scraped_text = "n/a" if scraped is None else f"{scraped:.2f}"
    return (
        f"| `{s['name']}` | `{s['judge']}` | {s['upstream']} | {s['concurrency']} | "
        f"{s['p50_ms']:.1f} | {s['p95_ms']:.1f} | {s['p99_ms']:.1f} | {s['rps']:.1f} | "
        f"{s['error_rate']:.3f} | {s['overhead_p50_ms']:.2f} | {s['overhead_p99_ms']:.2f} | "
        f"{scraped_text} |"
    )


def render(overhead: dict[str, Any], real: dict[str, Any] | None) -> str:
    env = overhead["environment"]
    fake_ms = overhead["fake_latency_ms"]
    lines = [
        HEADER,
        "",
        "# Latency and throughput",
        "",
        "Two measurements, kept apart on purpose.",
        "",
        f"**Service overhead** runs the real service against a stand-in backend that sleeps a "
        f"known {fake_ms:g} ms. That exercises the whole real path (httpx, the connection pool, "
        "the thread offload, the semaphore, schema decoding, metrics, logging) and replaces "
        "only the model's thinking time with a constant, so what is left is this service's own "
        "cost.",
        "",
        "**A real sample** runs against Ollama. Its p99 is a property of the model on that "
        "machine and says almost nothing about the server, which is exactly why the two are "
        "not averaged together.",
        "",
        "## Service overhead",
        "",
        f"Machine: {env['label']}. Python {env['python']}, {env['system']} {env['machine']}, "
        f"{env['cpu_count']} CPUs. Commit `{env['git_sha'][:12]}`, {env['generated_at']}.",
        "",
        "Latency in milliseconds. `overhead` is the request's own time minus model time and "
        "queue wait, measured inside the handler. `scraped p99` is the same quantity read back "
        "from the service's `/metrics`, as an independent estimate.",
        "",
        "| scenario | judge | upstream | conc. | p50 | p95 | p99 | rps | errors | overhead p50 |"
        " overhead p99 | scraped p99 |",
        "|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    lines += [_row(s) for s in overhead["scenarios"]]
    lines += [
        "",
        "What each scenario isolates:",
        "",
        "- `floor` — the mock judge, no I/O at all: the cost of ASGI, Pydantic, metrics and "
        "logging, and nothing else.",
        "- `rules` — the rule engine, with context validation on the path.",
        f"- `pooled` — the step judge against a backend that always takes {fake_ms:g} ms.",
        "- `degraded` — the same, with a tenth of requests hanging past the timeout.",
        "- `overload` — more offered load than the semaphore admits.",
        "",
    ]

    degraded = [s for s in overhead["scenarios"] if s["name"] == "degraded"]
    pooled8 = [s for s in overhead["scenarios"] if s["name"] == "pooled" and s["concurrency"] == 8]
    if degraded and pooled8:
        d, p = degraded[0], pooled8[0]
        failures = ", ".join(
            f"{count} answered {code}"
            for code, count in sorted(d["status_counts"].items())
            if code != "200"
        )
        lines += [
            "### Failure handling, measured",
            "",
            f"In `degraded` the injected tenth comes back as a timeout, not a crash: {failures}, "
            f"none of them 500. The median of everything else holds at {d['p50_ms']:.1f} ms "
            f"against {p['p50_ms']:.1f} ms in `pooled`, so a slow tenth does not poison the fast "
            "nine tenths.",
            "",
        ]

    pooled = [s for s in overhead["scenarios"] if s["name"] == "pooled"]
    if len(pooled) > 1:
        base = pooled[0]
        knee = None
        for previous, current in itertools.pairwise(pooled):
            doubled = current["p99_ms"] > 2 * base["p99_ms"]
            flat = current["rps"] < previous["rps"] * 1.05
            if doubled or flat:
                knee = current
                break
        if knee is not None:
            lines += [
                "### Saturation",
                "",
                f"Throughput climbs with concurrency to {max(s['rps'] for s in pooled):.0f} "
                f"requests per second and then stops. The knee is at concurrency "
                f"{knee['concurrency']}, where p99 reaches {knee['p99_ms']:.0f} ms against "
                f"{base['p99_ms']:.0f} ms at concurrency 1 while throughput no longer improves. "
                "That is the semaphore doing its job: past its limit, extra load becomes queue "
                "time rather than work.",
                "",
            ]

    overload = [s for s in overhead["scenarios"] if s["name"] == "overload"]
    if overload:
        o = overload[0]
        rejected = o["status_counts"].get("429", 0)
        lines += [
            "### Backpressure",
            "",
            f"At concurrency {o['concurrency']} against a limit of 4, "
            + (
                f"{rejected} of {o['n']} requests were refused with 429 and a `Retry-After` "
                "rather than queued without bound."
                if rejected
                else f"all {o['n']} requests were served, queued behind the semaphore "
                f"(p50 {o['p50_ms']:.0f} ms). Nothing was dropped."
            ),
            "",
        ]

    if real is not None:
        renv = real["environment"]
        lines += [
            "## A real model, for scale",
            "",
            f"{renv['label']}, {real['model']}. This is a small sample and it is here to show "
            "the ratio, not to characterise the model.",
            "",
            "| conc. | n | p50 (s) | p95 (s) | p99 (s) | model p50 (s) | rps |"
            " overhead p50 (ms) | overhead p99 (ms) | overhead share |",
            "|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
        ]
        for s in real["scenarios"]:
            share = s["overhead_p50_ms"] / s["p50_ms"] if s["p50_ms"] else 0.0
            lines.append(
                f"| {s['concurrency']} | {s['n']} | {s['p50_ms'] / 1000:.1f} | "
                f"{s['p95_ms'] / 1000:.1f} | {s['p99_ms'] / 1000:.1f} | "
                f"{s['model_ms_p50'] / 1000:.1f} | {s['rps']:.2f} | "
                f"{s['overhead_p50_ms']:.2f} | {s['overhead_p99_ms']:.2f} | {share:.4%} |"
            )
        lines += [
            "",
            "The latency in that table is a property of the model on that machine, not of this "
            "service. The service's own contribution is the overhead columns, and at "
            f"{min(s['overhead_p50_ms'] / s['p50_ms'] for s in real['scenarios']):.4%} of the "
            "total it is not what anyone waiting on this endpoint is waiting for.",
            "",
        ]
        if len(real["scenarios"]) > 1:
            first, last = real["scenarios"][0], real["scenarios"][-1]
            lines += [
                f"The concurrency column is the useful part. Going from {first['concurrency']} "
                f"to {last['concurrency']} concurrent requests multiplies latency by "
                f"{last['p50_ms'] / first['p50_ms']:.1f}x "
                f"({first['p50_ms'] / 1000:.1f}s to {last['p50_ms'] / 1000:.1f}s) and moves "
                f"throughput from {first['rps']:.2f} to only {last['rps']:.2f} requests per "
                "second. Ollama serialises per loaded model unless `OLLAMA_NUM_PARALLEL` says "
                "otherwise, so offering it more concurrency buys queue time rather than "
                "capacity. That is the measurement behind the rule `TJ_MAX_CONCURRENCY = "
                "OLLAMA_NUM_PARALLEL`.",
                "",
            ]

    lines += [
        "## Method",
        "",
        "- Closed loop: N workers each send one request and wait, so the reported quantity is "
        "latency at concurrency N and throughput is derived from it rather than targeted. "
        "There is no coordinated omission to correct for.",
        "- Percentiles are nearest-rank on the sorted sample. Raw per-request timings are kept "
        "in the JSON whenever there are 2000 or fewer, so every number here can be recomputed "
        "by hand.",
        "- A warmup request is discarded before each scenario.",
        '- Regenerate with `python bench/scenarios.py --label "<machine>"`, then '
        "`python bench/render.py`. CI runs `--check`, which re-renders from the committed JSON "
        "and fails on any difference.",
        "",
    ]
    return "\n".join(lines)


def headline(overhead: dict[str, Any], real: dict[str, Any] | None) -> str:
    """The few rows the main README carries, so it never disagrees with bench/README.md."""
    wanted = [("floor", 1), ("rules", 1), ("pooled", 8), ("degraded", 8), ("overload", 32)]
    by_key = {(s["name"], s["concurrency"]): s for s in overhead["scenarios"]}
    rows = [
        "| scenario | upstream | conc. | p50 | p99 | rps | errors | service overhead p99 |",
        "|---|---|---:|---:|---:|---:|---:|---:|",
    ]
    for name, concurrency in wanted:
        s = by_key.get((name, concurrency))
        if s is None:
            continue
        rows.append(
            f"| `{s['name']}` | {s['upstream']} | {s['concurrency']} | {s['p50_ms']:.1f} ms | "
            f"{s['p99_ms']:.1f} ms | {s['rps']:.0f} | {s['error_rate']:.3f} | "
            f"{s['overhead_p99_ms']:.2f} ms |"
        )
    if real is not None and real["scenarios"]:
        s = real["scenarios"][0]
        rows.append(
            f"| `real` | ollama {real['model']} | {s['concurrency']} | "
            f"{s['p50_ms'] / 1000:.1f} s | {s['p99_ms'] / 1000:.1f} s | {s['rps']:.2f} | "
            f"{s['error_rate']:.3f} | {s['overhead_p99_ms']:.2f} ms |"
        )
        note = (
            f"\nThe `real` row's latency belongs to {real['model']} on that machine. This "
            "service's own contribution is the last column, and it is the same order of "
            "magnitude in every row above it."
        )
    else:
        note = (
            "\nEvery row above runs against a stand-in backend with a known, fixed latency, so the "
            "last column is this service's own cost rather than a model's."
        )
    env = overhead["environment"]
    return (
        "\n".join(rows)
        + "\n"
        + note
        + (f"\n\nMeasured on {env['label']}, commit `{env['git_sha'][:12]}`.")
    )


def inject(readme: Path, block: str) -> bool:
    """Replace the marked region of the main README. Returns whether it changed."""
    text = readme.read_text()
    if BENCH_START not in text or BENCH_END not in text:
        return False
    head, rest = text.split(BENCH_START, 1)
    _, tail = rest.split(BENCH_END, 1)
    updated = f"{head}{BENCH_START}\n{block}\n{BENCH_END}{tail}"
    if updated == text:
        return False
    readme.write_text(updated)
    return True


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the file would change")
    parser.add_argument("--out", default=str(HERE / "README.md"))
    args = parser.parse_args()

    overhead_path = HERE / "results" / "overhead.json"
    if not overhead_path.exists():
        raise SystemExit(f"no benchmark results at {overhead_path}; run bench/scenarios.py first")
    overhead = json.loads(overhead_path.read_text())

    real_path = HERE / "results" / "real_sample.json"
    real = json.loads(real_path.read_text()) if real_path.exists() else None

    text = render(overhead, real)
    out = Path(args.out)
    main_readme = HERE.parent / "README.md"
    block = headline(overhead, real)

    if args.check:
        stale = []
        if (out.read_text() if out.exists() else "") != text:
            stale.append(str(out))
        before = main_readme.read_text()
        if inject(main_readme, block):
            main_readme.write_text(before)
            stale.append(str(main_readme))
        if stale:
            print("stale, run `python bench/render.py`: " + ", ".join(stale), file=sys.stderr)
            raise SystemExit(1)
        print("the committed tables match the committed results")
        return

    out.write_text(text)
    changed = inject(main_readme, block)
    print(f"wrote {out}" + (f" and updated {main_readme}" if changed else ""))


if __name__ == "__main__":
    main()
