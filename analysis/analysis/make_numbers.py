"""Emit paper/numbers.tex: every number the paper quotes, as a LaTeX macro.

Reads analysis/ci.json plus the raw JSONL and writes one \\newcommand per value,
so no result number is ever typed by hand in the prose. Deterministic; rerunning
produces a byte-identical file.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "paper" / "numbers.tex"

JUDGE_KEY = {
    "Rules": "programmatic",
    "Outcome": "outcome:qwen2.5:14b",
    "StepQ": "step:qwen2.5:14b",
    "StepL": "step:llama3.1:8b",
    "Selfcons": "selfcons3:qwen2.5:14b",
}
METRIC_KEY = {
    "Fone": "f1",
    "Silent": "silent_recall",
    "Loud": "loud_recall",
    "FA": "false_alarm_rate",
    "StepExact": "step_exact",
    "TypeF": "type_f1",
    "ECE": "ece",
    "Brier": "brier",
    "Precision": "precision",
}
TYPE_KEY = {
    "WrongTool": "wrong_tool",
    "HallucArg": "hallucinated_argument",
    "SkippedPre": "skipped_precondition",
    "IgnoredObs": "ignored_observation",
    "PrematureStop": "premature_stop",
    "UnsupClaim": "unsupported_claim",
}
COST = {"Rules": "0.0", "Outcome": "3.5", "StepQ": "10.4", "StepL": "1.5", "Selfcons": "30.2"}


def fmt(x: float, places: int = 3) -> str:
    return f"{x:.{places}f}"


def ci_str(cell: dict, places: int = 2) -> str:
    return f"[{cell['lo']:.{places}f}, {cell['hi']:.{places}f}]"


def main() -> None:
    ci = json.loads((ROOT / "analysis" / "ci.json").read_text())
    trajectories = [
        json.loads(line) for line in (DATA / "trajectories.jsonl").read_text().splitlines()
    ]
    verdicts = [json.loads(line) for line in (DATA / "verdicts.jsonl").read_text().splitlines()]
    label = {t["trajectory_id"]: t["label"] for t in trajectories}

    lines = [
        "% AUTO-GENERATED by analysis/make_numbers.py from analysis/ci.json and data/ --",
        "% do not edit by hand. Rerun `make numbers`.",
    ]

    def emit(name: str, value: str) -> None:
        lines.append(f"\\newcommand{{\\tj{name}}}{{{value}}}")

    for jname, jid in JUDGE_KEY.items():
        cells = ci["judges"][jid]
        for mname, mid in METRIC_KEY.items():
            if mid not in cells:
                continue
            cell = cells[mid]
            emit(f"{jname}{mname}", fmt(cell["point"]))
            degenerate = cell["hi"] - cell["lo"] < 1e-9
            emit(f"{jname}{mname}CI", "---" if degenerate else ci_str(cell))
        for tname, tid in TYPE_KEY.items():
            cell = cells[f"recall_{tid}"]
            emit(f"{jname}{tname}", fmt(cell["point"], 2))
            emit(f"{jname}{tname}CI", ci_str(cell))
        emit(f"{jname}Cost", COST[jname])
        emit(f"{jname}StepN", str(ci["extras"][jid]["step_scored_n"]))

    for dname, key in [
        ("DeltaOutcomeLoudSilent", "outcome_loud_minus_silent"),
        ("DeltaStepOutcomeSilent", "step_minus_outcome_silent"),
        ("DeltaStepRulesSilent", "step_minus_rules_silent"),
        ("DeltaSelfconsFone", "selfcons_minus_step_f1"),
        ("DeltaSelfconsSilent", "selfcons_minus_step_silent"),
        ("DeltaSelfconsTypeF", "selfcons_minus_step_type_f1"),
        ("DeltaSelfconsECE", "selfcons_minus_step_ece"),
        ("DeltaSelfconsStepExact", "selfcons_minus_step_step_exact"),
    ]:
        d = ci["deltas"][key]
        emit(dname, f"{d['point']:+.3f}")
        emit(f"{dname}CI", f"[{d['lo']:+.3f}, {d['hi']:+.3f}]")

    # Counts and derived quantities, recomputed from the raw files.
    by_judge: dict[str, list[dict]] = {}
    for v in verdicts:
        by_judge.setdefault(v["judge_id"], []).append(v)

    step = by_judge["step:qwen2.5:14b"]
    step_flags = [v for v in step if v["faulty"]]
    step_true = [v for v in step_flags if label[v["trajectory_id"]]["faulty"]]
    emit("StepQFlags", str(len(step_flags)))
    emit("StepQFlagsTrue", str(len(step_true)))

    llama_flags = sum(v["faulty"] for v in by_judge["step:llama3.1:8b"])
    emit("StepLFlags", str(llama_flags))

    outcome = by_judge["outcome:qwen2.5:14b"]
    conf92 = sum(1 for v in outcome if abs(v["confidence"] - 0.92) < 1e-9)
    emit("OutcomeConfNinetyTwo", str(conf92))
    pooled = sum(
        v["faulty"] for v in outcome if label[v["trajectory_id"]]["faulty"]
    ) / sum(1 for t in trajectories if t["label"]["faulty"])
    emit("OutcomePooledRecall", fmt(pooled, 2))

    sc = by_judge["selfcons3:qwen2.5:14b"]
    two_thirds = sum(1 for v in sc if abs(v["confidence"] - 2 / 3) < 1e-3)
    emit("SelfconsTwoThirds", str(two_thirds))
    emit("SelfconsUnanimous", str(len(sc) - two_thirds))

    def mean_tokens(judge: str) -> float:
        vs = by_judge[judge]
        return sum(v["completion_tokens"] for v in vs) / len(vs)

    emit("StepQMeanTokens", str(round(mean_tokens("step:qwen2.5:14b"))))
    emit("StepLMeanTokens", str(round(mean_tokens("step:llama3.1:8b"))))

    n = len(trajectories)
    n_faulty = sum(1 for t in trajectories if t["label"]["faulty"])
    n_silent = sum(
        1 for t in trajectories if t["label"]["faulty"] and t["label"]["outcome_correct"]
    )
    emit("NTraj", str(n))
    emit("NClean", str(n - n_faulty))
    emit("NFaulty", str(n_faulty))
    emit("NSilent", str(n_silent))
    emit("NLoud", str(n_faulty - n_silent))
    emit("NPerType", "50")
    emit("NVerdicts", str(len(verdicts)))
    emit("FAUpperBound", "0.036")  # Clopper-Pearson 95% upper bound on 0/100
    emit("NRestocking", "128")

    # Organic agent episodes.
    agent = [
        json.loads(line)
        for line in (DATA / "agent_trajectories.jsonl").read_text().splitlines()
    ]
    a_faulty = [t for t in agent if t["label"]["faulty"]]
    a_wrong = [t for t in agent if not t["label"]["outcome_correct"]]
    escalates = sum(
        1 for t in agent for s in t["steps"] if s["call"]["tool"] == "escalate"
    )
    eligibility = sum(
        1
        for t in agent
        if any(s["call"]["tool"] == "check_eligibility" for s in t["steps"])
    )
    emit("AgentN", str(len(agent)))
    emit("AgentFaulty", str(len(a_faulty)))
    emit("AgentWrongOutcome", str(len(a_wrong)))
    emit("AgentSilent", str(len([t for t in a_faulty if t["label"]["outcome_correct"]])))
    emit("AgentEscalates", str(escalates))
    emit("AgentEligibilityEpisodes", str(eligibility))

    # Rounded percentage forms for the abstract, and the two quoted confidences.
    j = ci["judges"]
    emit("OutcomeLoudPct", f"{round(j['outcome:qwen2.5:14b']['loud_recall']['point'] * 100)}\\%")
    emit("OutcomeSilentPct", f"{round(j['outcome:qwen2.5:14b']['silent_recall']['point'] * 100)}\\%")
    emit("OutcomeFAPct", f"{round(j['outcome:qwen2.5:14b']['false_alarm_rate']['point'] * 100)}\\%")
    emit("StepQSilentPct", f"{round(j['step:qwen2.5:14b']['silent_recall']['point'] * 100)}\\%")
    emit(
        "StepQUnsupMissPct",
        f"{round((1 - j['step:qwen2.5:14b']['recall_unsupported_claim']['point']) * 100)}\\%",
    )
    case = next(
        v for v in by_judge["step:qwen2.5:14b"]
        if v["trajectory_id"] == "INS-00000-unsupported_claim"
    )
    emit("CaseConf", f"{case['confidence']:.2f}")
    modal = max(
        {v["confidence"] for v in by_judge["outcome:qwen2.5:14b"]},
        key=lambda c: sum(1 for v in by_judge["outcome:qwen2.5:14b"] if v["confidence"] == c),
    )
    emit("OutcomeModalConf", f"{modal:.2f}")

    # Step-judge confusion counts the analysis section quotes.
    step_conf: dict[tuple[str, str], int] = {}
    for v in by_judge["step:qwen2.5:14b"]:
        lab = label[v["trajectory_id"]]
        if not lab["faulty"] or lab["failure_type"] is None:
            continue
        pred = v["failure_type"] if (v["faulty"] and v["failure_type"]) else "missed"
        step_conf[(lab["failure_type"], pred)] = step_conf.get((lab["failure_type"], pred), 0) + 1
    emit("StepQHallucAsWrong", str(step_conf.get(("hallucinated_argument", "wrong_tool"), 0)))
    emit("StepQUnsupMissed", str(step_conf.get(("unsupported_claim", "missed"), 0)))
    emit("StepQUnsupCaught", str(step_conf.get(("unsupported_claim", "unsupported_claim"), 0)))
    emit("StepQPremCorrect", str(step_conf.get(("premature_stop", "premature_stop"), 0)))
    emit("StepQPremAsUnsup", str(step_conf.get(("premature_stop", "unsupported_claim"), 0)))
    emit("StepQPremAsSkipped", str(step_conf.get(("premature_stop", "skipped_precondition"), 0)))

    # Step localisation within one index, per judge (never published in the repo tables).
    for jname, jid in JUDGE_KEY.items():
        if jid == "outcome:qwen2.5:14b":
            continue
        hits = total = 0
        for v in by_judge[jid]:
            lab = label[v["trajectory_id"]]
            if (
                lab["faulty"] and v["faulty"]
                and lab["failure_step"] is not None and v["failure_step"] is not None
            ):
                total += 1
                hits += abs(lab["failure_step"] - v["failure_step"]) <= 1
        emit(f"{jname}StepWithinOne", fmt(hits / total))

    # Token and latency totals for the appendix cost table.
    for jname, jid in JUDGE_KEY.items():
        vs = by_judge[jid]
        emit(f"{jname}PromptTok", f"{sum(v['prompt_tokens'] for v in vs):,}")
        emit(f"{jname}ComplTok", f"{sum(v['completion_tokens'] for v in vs):,}")
    total_latency = sum(v["latency_s"] for v in verdicts)
    emit("TotalHours", f"{total_latency / 3600:.2f}")

    # Organic episodes: fault concentration by stratum (round-robin on instance index).
    strata = ["happy", "restocking", "expired", "non_refundable", "wrong_customer",
              "already_refunded"]
    per_stratum: dict[str, int] = {s: 0 for s in strata}
    for t in agent:
        if t["label"]["faulty"]:
            per_stratum[strata[int(t["instance_id"][4:]) % 6]] += 1
    emit("AgentAlreadyRefundedFaulty", str(per_stratum["already_refunded"]))
    emit("AgentWrongCustomerFaulty", str(per_stratum["wrong_customer"]))

    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(lines) - 2} macros)")


if __name__ == "__main__":
    main()
